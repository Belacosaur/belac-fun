import { expect, test } from "@playwright/test";

test("the orbital studio reads the deployed wallet instead of simulated returns", async ({ page }) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width: 1600, height: 1050 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/station");
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-ready", "true", { timeout: 60000 });
  await expect(page.getByRole("status")).toContainText("Wallet connected", { timeout: 30000 });
  await expect(page.getByRole("button", { name: "Pause simulation" })).toHaveCount(0);
  await page.screenshot({ path: "../../artifacts/live-overview.png" });
  await page.getByRole("button", { name: "All positions" }).click();
  await expect(page.locator(".positions-table tbody tr")).toHaveCount(10);
  const rows = page.locator(".positions-table tbody tr");
  await expect(rows.nth(1)).toContainText("Raydium");
  await expect(rows.nth(2)).toContainText("Jupiter Perps");
  await expect(rows.nth(3)).toContainText("Pacifica");
  await expect(rows.nth(7)).toContainText("Orca");
  await expect(rows.nth(8)).toContainText("Ript");
  await expect(rows.nth(8)).toContainText("Pending");
  await expect(rows.nth(8)).toContainText("custom challenge pack");
  await expect(rows.nth(0)).toContainText("Quotes connected");
  await expect(rows.nth(1)).toContainText("Quotes connected");
  await expect(rows.nth(7)).toContainText("Position reader connected");
  await expect(rows.nth(6)).toContainText("Chain reader connected");
  await expect(rows.nth(6)).toContainText("Buy an existing memecoin");
  await expect(rows.nth(9)).toContainText("Create & launch our own memecoin");
  await expect(page.locator(".positions-panel")).not.toContainText("Deferred");
  await expect(page.locator(".positions-panel")).toContainText("HBFn6VWPLNt44i8zqUoNs4mMtqyyxNTyWwQqfH5TBx8j");
  await page.screenshot({ path: "../../artifacts/live-connections.png" });
  await page.getByRole("button", { name: "Close positions" }).click();
  await page.getByRole("button", { name: "Station 6: Kamino", exact: true }).click();
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-active-station", "6");
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await page.screenshot({ path: "../../artifacts/live-kamino.png" });
  await page.getByRole("button", { name: "Station 9: Ript", exact: true }).click();
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-active-station", "9");
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await page.screenshot({ path: "../../artifacts/live-ript.png" });
  await page.getByRole("button", { name: "Station 8: Orca", exact: true }).click();
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-active-station", "8");
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await page.screenshot({ path: "../../artifacts/live-orca.png" });
});
