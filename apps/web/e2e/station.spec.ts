import { expect, test } from "@playwright/test";

test("the circular studio starts at the overview, navigates agents and shows the whole room", async ({ page }) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/station");
  const scene = page.locator(".studio-scene");
  await expect(scene).toHaveAttribute("data-ready", "true", { timeout: 45000 });
  await expect(scene).toHaveAttribute("data-active-station", "0");
  await expect(page.locator(".station-rail button")).toHaveCount(11);
  await expect(page.getByRole("button", { name: "Say hello" })).toBeDisabled();
  const total = page.locator(".footer-stat strong").first();
  const opening = await total.textContent();
  await expect(total).not.toHaveText(opening!, { timeout: 16000 });
  await page.getByRole("button", { name: "Pause simulation" }).click();
  const paused = await total.textContent();
  await page.waitForTimeout(4100);
  await expect(total).toHaveText(paused!);
  await page.screenshot({ path: "../../artifacts/room-overview.png" });
  await page.getByRole("button", { name: "Station 6: Kamino", exact: true }).click();
  await expect(scene).toHaveAttribute("data-active-station", "6", { timeout: 15000 });
  await expect(scene).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await page.screenshot({ path: "../../artifacts/station-centre.png" });
  await page.getByRole("button", { name: "Next station", exact: true }).click();
  await expect(scene).toHaveAttribute("data-active-station", "7", { timeout: 15000 });
  await expect(scene).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await expect(page.locator('[data-agent="6"]')).toHaveAttribute("data-pose", "working", { timeout: 15000 });
  const canvas = await page.locator("canvas").boundingBox();
  if (!canvas) throw new Error("Studio canvas did not render");
  await page.mouse.move(canvas.x + canvas.width * .5, canvas.y + canvas.height * .65);
  await page.mouse.down();
  await page.mouse.move(canvas.x + canvas.width * .5 - 127, canvas.y + canvas.height * .65, { steps: 8 });
  await page.mouse.up();
  await expect(scene).toHaveAttribute("data-active-station", "8", { timeout: 15000 });
  await page.keyboard.press("Home");
  await expect(scene).toHaveAttribute("data-active-station", "0", { timeout: 15000 });
  await page.getByRole("button", { name: "Bird’s-eye" }).click();
  await expect(page.locator(".room-map-label")).toHaveCount(11);
  await expect(page.locator('[data-agent="7"]')).toHaveAttribute("data-pose", "working", { timeout: 15000 });
  await page.waitForTimeout(3200);
  await page.screenshot({ path: "../../artifacts/station-birdseye.png" });
  await page.getByRole("button", { name: "Visit Jupiter Swap", exact: true }).click();
  await expect(scene).toHaveAttribute("data-active-station", "1", { timeout: 15000 });
  await expect(page.getByRole("button", { name: "Centre view" })).toHaveAttribute("aria-pressed", "true");
  await expect(scene).toHaveAttribute("data-agent-pose", "greeting", { timeout: 15000 });
  await page.getByRole("button", { name: "All positions" }).click();
  await expect(page.locator(".positions-panel tbody tr")).toHaveCount(10);
  await expect(page.locator(".positions-total strong").first()).toHaveText(paused!);
  expect(errors).toEqual([]);
});

test("mobile studio keeps all positions reachable and fits the whole room", async ({ page }) => {
  test.setTimeout(60000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/station");
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-ready", "true", { timeout: 45000 });
  await page.getByRole("button", { name: "Pause simulation" }).click();
  await expect(page.locator(".studio-footer")).toBeInViewport();
  await page.screenshot({ path: "../../artifacts/station-mobile.png" });
  await page.getByRole("button", { name: "Station 10: Pump.fun", exact: true }).click();
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-active-station", "10");
  await page.getByRole("button", { name: "Next station", exact: true }).click();
  await expect(page.locator(".studio-scene")).toHaveAttribute("data-active-station", "0");
  await page.getByRole("button", { name: "Bird’s-eye" }).click();
  await expect(page.locator(".room-map-label")).toHaveCount(11);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: "../../artifacts/room-mobile-birdseye.png" });
  await page.getByRole("button", { name: "All positions" }).click();
  await expect(page.getByRole("button", { name: "Close positions" })).toBeInViewport();
});
